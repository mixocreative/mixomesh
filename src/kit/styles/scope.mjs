// Builds kit.scoped.css from the UNCHANGED mixo-app-style copies (tokens.css, base.css;
// skill repo mixocreative/mixo-app-style @ fc11115). Every selector is moved under `.mx-kit`
// so the kit can sit beside legacy panels without restyling them. Never edit the copies;
// re-copy from S:\ai\skills\mixo-app-style, then `node src/kit/styles/scope.mjs`.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import postcss from 'postcss';

const here = (f) => fileURLToPath(new URL(f, import.meta.url));

export function scopeSelector(sel) {
  const s = sel.trim();
  if (s === '*') return '.mx-kit, .mx-kit *';
  if (s === 'body' || s === 'html' || s === ':root') return '.mx-kit';
  if (s.startsWith(':root')) return '.mx-kit' + s.slice(5);
  if (s.startsWith('[lang')) return `.mx-kit${s}, .mx-kit ${s}`;
  return `.mx-kit ${s}`;
}

export function buildScoped() {
  const header = '/* GENERATED by scope.mjs from tokens.css + base.css (mixo-app-style @ fc11115). Do not edit. */\n';
  let out = header;
  for (const f of ['tokens.css', 'base.css']) {
    const root = postcss.parse(readFileSync(here(f), 'utf8'));
    root.walkRules((rule) => {
      if (rule.parent?.type === 'atrule' && /keyframes/.test(rule.parent.name)) return;
      rule.selectors = rule.selectors.flatMap((s) => scopeSelector(s).split(/,(?![^(]*\))/));
    });
    out += `\n/* ---- ${f} ---- */\n${root.toString()}\n`;
  }
  return out;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(here('kit.scoped.css'), buildScoped());
}
